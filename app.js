/** Is this a date a person could have meant, or a year still being typed? */
function plausibleExam(v) {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(v)) return false;
  const y = Number(v.slice(0, 4));
  return y >= EXAM_MIN_YEAR && y <= EXAM_MAX_YEAR;
}

